fn main() {
    // Integer
    let age: i32 = 25;

    // Floating-point number
    let height: f64 = 5.9;

    // Boolean
    let is_learning: bool = true;

    // Character
    let grade: char = 'A';

    println!("Age: {age}");
    println!("Height: {height}");
    println!("Learning Rust: {is_learning}");
    println!("Grade: {grade}");
}
